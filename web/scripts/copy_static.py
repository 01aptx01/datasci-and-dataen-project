#!/usr/bin/env python3
"""Copy the HTML shell and verified runtime policy beside compiled modules."""

from __future__ import annotations

import shutil
import json
from pathlib import Path

WEB_ROOT = Path(__file__).resolve().parents[1]
DIST = (WEB_ROOT / "dist").resolve()

if DIST.parent != WEB_ROOT.resolve():
    raise SystemExit("Refusing to write outside web/dist")
DIST.mkdir(parents=True, exist_ok=True)
for source, filename in ((WEB_ROOT / "index.html", "index.html"), (WEB_ROOT / "src" / "styles.css", "styles.css"), (WEB_ROOT / "snapshot.policy.json", "snapshot.policy.json")):
    shutil.copy2(source, DIST / filename)

# Publish only the verified, allowlisted snapshot outputs generated by
# prepare_snapshot.py. The handoff ZIP itself and its internal manifests stay
# outside the browser bundle.
policy = json.loads((WEB_ROOT / "snapshot.policy.json").read_text(encoding="utf-8"))
evaluation_id = policy["identity"]["evaluationId"]
snapshot_source = WEB_ROOT / "public" / "snapshots" / evaluation_id
snapshot_manifest = snapshot_source / "dashboard_snapshot_manifest.json"
if snapshot_manifest.is_file():
    manifest = json.loads(snapshot_manifest.read_text(encoding="utf-8"))
    if manifest.get("evaluationId") != evaluation_id or manifest.get("replayId") != policy["identity"]["replayId"]:
        raise SystemExit("Refusing to publish a snapshot with mismatched Evaluation or Replay ID")
    output_dir = DIST / "snapshots" / evaluation_id
    output_dir.mkdir(parents=True, exist_ok=True)
    outputs = [
        snapshot_manifest,
        snapshot_source / policy["publicOutputs"]["forecastAudit"],
        snapshot_source / policy["publicOutputs"]["evaluation"],
    ]
    for source in outputs:
        if source.parent.resolve() != snapshot_source.resolve() or not source.is_file():
            raise SystemExit(f"Refusing to publish a missing or out-of-scope snapshot file: {source.name}")
        shutil.copy2(source, output_dir / source.name)
print(f"STATIC BUILD READY: {DIST}")
